# Deploys the AWS side and generates firmware/security_hub/aws_secrets.h.
# Requires the AWS CLI configured for your account (aws configure). Safe to re-run.
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$cfg = Get-Content (Join-Path $root 'config.json') -Raw | ConvertFrom-Json
$certDir = Join-Path $root '.certs'
$secretsPath = Join-Path $root '..\firmware\security_hub\aws_secrets.h'
$env:AWS_DEFAULT_REGION = $cfg.region

function Invoke-Aws {
    $out = & aws @args --output json
    if ($LASTEXITCODE -ne 0) { throw "aws $($args -join ' ') failed" }
    if ($out) { return ($out | Out-String | ConvertFrom-Json) }
}

Write-Host "1/6 CloudFormation stack '$($cfg.stack_name)' ($($cfg.region))"
$t = $cfg.thresholds
& aws cloudformation deploy --stack-name $cfg.stack_name --template-file (Join-Path $root 'template.yaml') `
    --capabilities CAPABILITY_IAM --no-fail-on-empty-changeset --parameter-overrides `
    "ThingName=$($cfg.thing_name)" "TopicPrefix=$($cfg.topic_prefix)" "TempOn=$($t.temp_on)" "TempOff=$($t.temp_off)" `
    "GasOn=$($t.gas_on)" "GasOff=$($t.gas_off)" "RetentionDays=$($cfg.retention_days)"
if ($LASTEXITCODE -ne 0) { throw 'CloudFormation deploy failed' }
$outputs = @{}
(Invoke-Aws cloudformation describe-stacks --stack-name $cfg.stack_name).Stacks[0].Outputs |
    ForEach-Object { $outputs[$_.OutputKey] = $_.OutputValue }

Write-Host '2/6 Lambda code'
$zip = Join-Path $env:TEMP 'iot-guvenlik-decide.zip'
Compress-Archive -Path (Join-Path $root 'lambda\decide.py') -DestinationPath $zip -Force
Invoke-Aws lambda update-function-code --function-name $outputs.DecisionFunctionName --zip-file "fileb://$zip" | Out-Null

Write-Host "3/6 Thing '$($cfg.thing_name)'"
& aws iot describe-thing --thing-name $cfg.thing_name *> $null
if ($LASTEXITCODE -ne 0) { Invoke-Aws iot create-thing --thing-name $cfg.thing_name | Out-Null }

Write-Host '4/6 Device certificate'
New-Item -ItemType Directory -Force $certDir | Out-Null
$certPem = Join-Path $certDir "$($cfg.thing_name).cert.pem"
$keyPem = Join-Path $certDir "$($cfg.thing_name).private.key"
$arnFile = Join-Path $certDir "$($cfg.thing_name).cert-arn.txt"
if (-not (Test-Path $certPem)) {
    $cert = Invoke-Aws iot create-keys-and-certificate --set-as-active `
        --certificate-pem-outfile $certPem --private-key-outfile $keyPem
    Set-Content -Path $arnFile -Value $cert.certificateArn -NoNewline
}
$certArn = (Get-Content $arnFile -Raw).Trim()
Invoke-Aws iot attach-policy --policy-name $outputs.DevicePolicyName --target $certArn | Out-Null
Invoke-Aws iot attach-thing-principal --thing-name $cfg.thing_name --principal $certArn | Out-Null

Write-Host '5/6 Amazon root CA'
$rootCa = Join-Path $certDir 'AmazonRootCA1.pem'
if (-not (Test-Path $rootCa)) {
    Invoke-WebRequest -Uri 'https://www.amazontrust.com/repository/AmazonRootCA1.pem' -OutFile $rootCa -UseBasicParsing
}

Write-Host '6/6 Firmware secrets'
$endpoint = (Invoke-Aws iot describe-endpoint --endpoint-type iot:Data-ATS).endpointAddress
$pem = { param($path) (Get-Content $path -Raw).Trim() }
$header = @"
#pragma once
// Generated by cloud/deploy.ps1 - do not edit, do not commit.
namespace AwsSecrets {
constexpr const char* kEndpoint = "$endpoint";
constexpr const char* kThingName = "$($cfg.thing_name)";
constexpr const char* kTopicPrefix = "$($cfg.topic_prefix)";
constexpr const char* kRootCa = R"PEM(
$(& $pem $rootCa)
)PEM";
constexpr const char* kDeviceCert = R"PEM(
$(& $pem $certPem)
)PEM";
constexpr const char* kPrivateKey = R"PEM(
$(& $pem $keyPem)
)PEM";
}  // namespace AwsSecrets
"@
[IO.File]::WriteAllText((Resolve-Path (Split-Path $secretsPath)).Path + '\aws_secrets.h', $header.Replace("`r`n", "`n"))

Write-Host ''
Write-Host "Done. Endpoint: $endpoint"
Write-Host "Tables: $($outputs.TelemetryTableName), $($outputs.EventsTableName)"
Write-Host 'Next: compile and upload firmware/security_hub (it now connects to AWS IoT Core).'
